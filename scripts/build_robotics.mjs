const escape = (text) => String(text).replace(/[&<>"']/g, (c) => ({'&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;'}[c]));
const slugify = (text) => text.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'section';

export function dateValue(value, field) {
  const result = value instanceof Date ? value.toISOString().slice(0, 10) : value;
  if (typeof result !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(result) || Number.isNaN(Date.parse(result)) || new Date(result).toISOString().slice(0, 10) !== result) {
    throw new Error(`${field} must be a valid YYYY-MM-DD date`);
  }
  return result;
}
function validateSeriesMetadata(data) {
  if (data.series !== undefined && (typeof data.series !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(data.series))) throw new Error('series must be a series id from content/robotics/series.json, such as so101-control');
  if (data.part !== undefined && (!Number.isInteger(data.part) || data.part < 0)) throw new Error('part must be a non-negative integer');
  if (data.series && data.part === undefined) throw new Error('part is required when series is set');
  if (data.track !== undefined && !TRACKS[data.track]) throw new Error(`track must be one of: ${Object.keys(TRACKS).join(', ')}`);
  if (data.track !== undefined && !data.series) throw new Error('track requires series');
}
// Tags group essays for the search and the tag filter on the Robotics index.
function validateTags(data) {
  if (data.tags === undefined) return;
  if (!Array.isArray(data.tags) || data.tags.length < 2 || data.tags.length > 4) throw new Error('tags must be a list of 2 to 4 short tags');
  const seen = new Set();
  for (const tag of data.tags) {
    if (typeof tag !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(tag)) throw new Error(`tags must be short lowercase words: ${String(tag)}`);
    if (seen.has(tag)) throw new Error(`Duplicate tag ${tag}`);
    seen.add(tag);
  }
}
// A section is a named shelf of essays with its own index page, for example the papers I find fascinating.
// An essay joins one with `section: 'recent-papers'`. The index lives at /robotics/<section>/.
const SECTIONS = {
  'recent-papers': {
    name: 'Recent papers',
    eyebrow: 'Recent papers / robotics',
    heading: 'Recent papers I find fascinating.',
    intro: 'Short write-ups of new robotics papers that change how I think about the field. Each one says what the paper does, what it measured, and what I would check before trusting it.',
    description: 'New robotics papers worth reading, explained with the setup behind every number.',
  },
};
function validateSection(data) {
  if (data.section !== undefined && !SECTIONS[data.section]) throw new Error(`section must be one of: ${Object.keys(SECTIONS).join(', ')}`);
}
// An essay about one paper may name it. The header then shows the paper's date and link.
function validatePaper(data) {
  if (data.paper === undefined) return;
  const paper = data.paper;
  if (!paper || typeof paper !== 'object' || Array.isArray(paper)) throw new Error('paper must be a map with title and url');
  const unknown = Object.keys(paper).filter((key) => !['title', 'url', 'date', 'project', 'code'].includes(key));
  if (unknown.length) throw new Error(`paper has unknown field ${unknown[0]}`);
  if (typeof paper.title !== 'string' || !paper.title.trim()) throw new Error('paper.title must be a non-empty string');
  for (const key of ['url', 'project', 'code']) {
    if (paper[key] === undefined && key !== 'url') continue;
    let url;
    try { url = new URL(paper[key]); } catch { throw new Error(`paper.${key} must be an HTTPS URL`); }
    if (url.protocol !== 'https:' || url.username || url.password) throw new Error(`paper.${key} must be an HTTPS URL`);
  }
  if (paper.date !== undefined) dateValue(paper.date, 'paper.date');
}
// Published cards require an article figure/frame under /assets/ and descriptive alt text.
function validateThumbnail(data, root) {
  if (data.thumbnail === undefined) {
    if (data.draft === true) return;
    throw new Error('published article requires thumbnail and thumbnail_alt frontmatter');
  }
  if (typeof data.thumbnail !== 'string' || !/^\/assets\/[\w./-]+$/.test(data.thumbnail) || data.thumbnail.includes('..')) throw new Error('thumbnail must be a path under /assets/');
  if (!fs.existsSync(path.join(root, data.thumbnail))) throw new Error(`thumbnail file not found: ${data.thumbnail}`);
  if (typeof data.thumbnail_alt !== 'string' || !data.thumbnail_alt.trim()) throw new Error('thumbnail needs thumbnail_alt text');
}
// content/robotics/series.json names each series once: {"<id>": {"title": ..., "subtitle": ..., "description": ...}}.
// The subtitle is optional. A part joins with `series: '<id>'` and `part: <n>`. The title, subtitle and description show on every page that lists the series.
function readSeries(sourceDir) {
  const file = path.join(sourceDir, 'series.json');
  if (!fs.existsSync(file)) return {};
  let data;
  try { data = JSON.parse(fs.readFileSync(file, 'utf8')); } catch (error) { throw new Error(`series.json must be valid JSON: ${error.message}`); }
  if (!data || typeof data !== 'object' || Array.isArray(data)) throw new Error('series.json must be an object');
  for (const [id, series] of Object.entries(data)) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id)) throw new Error(`series.json: invalid series id ${id}`);
    if (!series || typeof series !== 'object' || Array.isArray(series)) throw new Error(`series.json: ${id} must be a map with title and description`);
    const unknown = Object.keys(series).filter((key) => !['title', 'subtitle', 'description'].includes(key));
    if (unknown.length) throw new Error(`series.json: ${id} has unknown field ${unknown[0]}`);
    for (const key of ['title', 'description']) {
      if (typeof series[key] !== 'string' || !series[key].trim()) throw new Error(`series.json: ${id} needs a ${key}`);
    }
    if (series.subtitle !== undefined && (typeof series.subtitle !== 'string' || !series.subtitle.trim())) throw new Error(`series.json: ${id} subtitle must be non-empty text`);
  }
  return data;
}
// A track marks a series part of a different kind (for example the hardware side of a control series).
// It gives the part its own accent colour and a label wherever the series is listed.
const TRACKS = {hardware:'Hardware'};
const trackClass = (article) => article.track ? ` track-${article.track}` : '';
const trackLabel = (article) => article.track ? ` · ${TRACKS[article.track]}` : '';
const htmlText = (value) => value.replace(/<(script|style)\b[^>]*>[\s\S]*?<\/\1>/gi, ' ').replace(/<!--[\s\S]*?-->/g, ' ').replace(/<[^>]+>/g, ' ');
const displayDate = (value) => new Intl.DateTimeFormat('en', {year:'numeric', month:'long', day:'numeric', timeZone:'UTC'}).format(new Date(value));
const shortDate = (value) => new Intl.DateTimeFormat('en', {month:'short', day:'numeric', timeZone:'UTC'}).format(new Date(value));
// The first and last publication dates of a series, for example "October 2–15, 2026".
export function dateRange(first, last) {
  if (first === last) return displayDate(first);
  return new Intl.DateTimeFormat('en', {year:'numeric', month:'long', day:'numeric', timeZone:'UTC'}).formatRange(new Date(first), new Date(last));
}

export function renderArticle(source, root = ROOT, html = undefined) {
  const {data, content} = matter(source);
  for (const field of ['title', 'description']) {
    if (typeof data[field] !== 'string' || !data[field].trim()) throw new Error(`Missing frontmatter ${field}`);
  }
  const date = dateValue(data.date, 'date');
  const updated = data.updated ? dateValue(data.updated, 'updated') : date;
  if (data.draft !== undefined && typeof data.draft !== 'boolean') throw new Error('draft must be true or false');
  if (data.layout !== undefined && !['essay', 'short'].includes(data.layout)) throw new Error('layout must be essay or short when provided');
  if (data.code_highlight !== undefined && typeof data.code_highlight !== 'boolean') throw new Error('code_highlight must be true or false');
  validateSeriesMetadata(data);
  validateTags(data);
  validatePaper(data);
  if (updated < date) throw new Error('updated cannot be earlier than date');
  const paper = data.paper ? {...data.paper, date:data.paper.date === undefined ? undefined : dateValue(data.paper.date, 'paper.date')} : undefined;
  // A short article is one authored HTML body, for example a blackboard canvas between two short paragraphs.
  // Its frontmatter lives in <slug>.md and its body in <slug>.html beside it.
  if (data.layout === 'short') {
    if (content.trim()) throw new Error('A short article keeps its body in the .html file beside it; leave the Markdown body empty');
    if (typeof html !== 'string' || !html.trim()) throw new Error('A short article needs a non-empty .html body beside its .md file');
    if (/<h1\b/i.test(html)) throw new Error('Use H2 or deeper in articles; title supplies H1');
    // Drawings carry long accessible descriptions; reading time counts the prose around them.
    const words = htmlText(html.replace(/<svg\b[\s\S]*?<\/svg>/gi, ' ')).trim().split(/\s+/).filter(Boolean).length;
    const components = {timeline:false, geometry:false, so101:false, market:false, futures:false};
    return {...data, paper, tags:data.tags ? [...data.tags] : [], date, updated, body:html, headings:[], components, readingMinutes:Math.max(1, Math.ceil(words / 220))};
  }
  if (html !== undefined) throw new Error('Only a short article (layout: short) may have an .html body');
  // An article that sets code_highlight colors its python code blocks; markdown-it wraps the result in <pre><code>.
  const highlight = data.code_highlight ? (code, lang) => (lang === 'python' ? highlightPython(code) : '') : null;
  const md = new MarkdownIt({html:true, linkify:true, typographer:false, highlight}).use(katex, {
    delimiters:'dollars', throwOnError:true, trust:false, output:'htmlAndMathml',
  });
  const headings = [];
  const ids = new Set();
  const components = {timeline:false, geometry:false, so101:false, market:false, futures:false};
  md.core.ruler.push('article-structure', (state) => {
    for (let i = 0; i < state.tokens.length; i++) {
      const token = state.tokens[i];
      if (token.type === 'html_block' && /<figure\b[^>]*\bclass=["'][^"']*\brf-figure\b/.test(token.content)) components.futures = true;
      if (token.type === 'heading_open') {
        if (token.tag === 'h1') throw new Error('Use H2 or deeper in articles; title supplies H1');
        const inline = state.tokens[i + 1];
        const title = inline.children.filter((child) => ['text', 'code_inline', 'math_inline', 'softbreak'].includes(child.type)).map((child) => child.type === 'softbreak' ? ' ' : child.content).join('');
        const base = slugify(title);
        let id = `section-${base}`;
        let count = 1;
        while (ids.has(id)) id = `section-${base}-${++count}`;
        ids.add(id);
        token.attrSet('id', id);
        token.meta = {...token.meta, title};
      }
      if (token.type === 'paragraph_open') {
        const inline = state.tokens[i + 1];
        if (inline?.children?.length === 1 && inline.children[0].type === 'image') {
          token.tag = 'figure';
          token.attrSet('class', 'article-figure');
          state.tokens[i + 2].tag = 'figure';
        }
      }
    }
    const headingIds = new Set(ids);
    let currentHeading = null;
    for (const token of state.tokens) {
      if (token.type === 'heading_open') currentHeading = token.attrGet('id');
      if (token.type === 'heading_open' && ['h2', 'h3'].includes(token.tag)) {
        headings.push({id:token.attrGet('id'), title:token.meta.title, level:token.tag});
      }
      if (token.type === 'fence' && token.info.trim() === 'robotics-market') {
        if (components.market) throw new Error('Only one robotics-market per article');
        token.meta = {...token.meta, market:parseMarket(token.content, root)};
        components.market = true;
      }
      if (token.type === 'fence' && token.info.trim() === 'robotics-arm') {
        if (token.content.trim()) throw new Error('robotics-arm does not accept content');
        if (components.geometry) throw new Error('Only one robotics-arm widget per article');
        token.meta = {...token.meta, geometry:true, geometryAnchor:currentHeading};
        components.geometry = true;
      }
      if (token.type === 'fence' && token.info.trim() === 'robotics-timeline') {
        token.meta = {...token.meta, timeline:parseTimeline(token.content, {root, headingIds, usedIds:ids})};
        const timeline = token.meta.timeline;
        headings.push({id:`${timeline.id}-heading`, title:timeline.heading, level:'h2'});
        components.timeline = true;
      }
      if (token.type === 'fence' && token.info.trim() === 'so101-widget') {
        let config;
        try { config = JSON.parse(token.content); } catch (error) { throw new Error(`so101-widget must contain valid JSON: ${error.message}`); }
        if (!config || typeof config !== 'object' || Array.isArray(config)) throw new Error('so101-widget must contain a JSON object');
        if (typeof config.type !== 'string' || !config.type.trim()) throw new Error('so101-widget requires a type');
        if (typeof config.fallback !== 'string' || !config.fallback.trim()) throw new Error('so101-widget requires a fallback');
        token.meta = {...token.meta, so101:config};
        components.so101 = true;
      }
    }
  });
  const renderFence = md.renderer.rules.fence;
  md.renderer.rules.fence = (tokens, index, options, environment, renderer) => {
    if (tokens[index].info.trim() === 'robotics-value-loop') {
      if (tokens[index].content.trim()) throw new Error('robotics-value-loop does not accept content');
      return renderValueLoop();
    }
    if (tokens[index].meta?.market) return renderMarket(tokens[index].meta.market);
    if (tokens[index].meta?.timeline) return renderTimeline(tokens[index].meta.timeline);
    if (tokens[index].meta?.geometry) return template('arm-demo.html', root, {
      arm_article_href:`#${tokens[index].meta.geometryAnchor || 'main'}`,
      arm_article_label:tokens[index].meta.geometryAnchor ? 'Back to the section' : 'Back to the essay',
    });
    if (tokens[index].meta?.so101) {
      const config = tokens[index].meta.so101;
      return `<figure class="so101-widget" data-type="${escape(config.type)}" data-config='${escape(JSON.stringify(config))}'><div class="so101-widget-fallback">${escape(config.fallback)}</div></figure>`;
    }
    return renderFence(tokens, index, options, environment, renderer);
  };
  md.renderer.rules.image = (tokens, index) => {
    const token = tokens[index];
    const src = token.attrGet('src');
    const alt = md.renderer.renderInlineAsText(token.children, md.options, {});
    if (!alt.trim()) throw new Error(`Image needs descriptive alt text: ${src}`);
    if (!src.startsWith('/assets/robotics/') || src.includes('..')) throw new Error(`Image must use /assets/robotics/: ${src}`);
    const filename = path.join(root, src);
    const bytes = fs.readFileSync(filename);
    if (!bytes.subarray(0, 8).equals(Buffer.from([137,80,78,71,13,10,26,10]))) throw new Error(`Use a PNG diagram: ${src}`);
    const dimensions = `width="${bytes.readUInt32BE(16)}" height="${bytes.readUInt32BE(20)}"`;
    const title = token.attrGet('title');
    return `<a class="figure-link" href="${escape(src)}" aria-label="${escape(`Open full image: ${alt}`)}"><img src="${escape(src)}" alt="${escape(alt)}" ${dimensions} loading="lazy" decoding="async"></a>${title ? `<figcaption>${escape(title)}</figcaption>` : ''}`;
  };
  md.renderer.rules.table_open = () => '<div class="table-scroll" role="region" aria-label="Table" tabindex="0"><table>\n';
  md.renderer.rules.table_close = () => '</table></div>\n';
  const environment = {};
  const tokens = md.parse(content, environment);
  const body = md.renderer.render(tokens, md.options, environment);
  if (body.includes('katex-error')) throw new Error('Math rendering failed');
  // Count authored prose before KaTeX turns each equation into HTML and MathML.
  const prose = tokens.flatMap((token) => {
    if (token.type === 'html_block') return [htmlText(token.content)];
    if (token.meta?.timeline) return [timelineProse(token.meta.timeline)];
    if (token.meta?.geometry) return [];
    if (['fence', 'code_block'].includes(token.type)) return [token.content];
    if (token.type !== 'inline') return [];
    return token.children.flatMap((child) => {
      if (['text', 'code_inline'].includes(child.type)) return [child.content];
      if (child.type === 'html_inline') return [htmlText(child.content)];
      if (child.type === 'image') return [child.attrGet('title') || ''];
      return [];
    });
  }).join(' ');
  const words = prose.trim().split(/\s+/).filter(Boolean).length;
  return {...data, paper, tags:data.tags ? [...data.tags] : [], date, updated, body, headings, components, readingMinutes:Math.max(1, Math.ceil(words / 220))};
}

function template(name, root = ROOT, values = {}) {
  const local = path.join(root, 'scripts/templates', name);
  const filename = fs.existsSync(local) ? local : path.join(ROOT, 'scripts/templates', name);
  return fs.readFileSync(filename, 'utf8').replace(/\{\{([a-z_]+)\}\}/g, (_, key) => {
    if (!(key in values)) throw new Error(`Unknown ${name} template token: ${key}`);
    return values[key];
  }).trim();
}
function assetVersion(root, ...filenames) {
  const hash = createHash('sha256');
  for (const filename of filenames) {
    const local = path.join(root, filename);
    const file = fs.existsSync(local) ? local : path.join(ROOT, filename);
    hash.update(fs.readFileSync(file));
  }
  return hash.digest('hex').slice(0, 12);
}
// An article may ship its own styles and module script beside its figures, at assets/robotics/<slug>/article.css and article.js.
function articleAssets(article, root) {
  const local = (filename) => fs.existsSync(path.join(root, filename));
  const css = `assets/robotics/${article.slug}/article.css`;
  const js = `assets/robotics/${article.slug}/article.js`;
  return `${local(css) ? `<link rel="stylesheet" href="/${css}?v=${assetVersion(root, css)}">` : ''}${local(js) ? `<script type="module" src="/${js}?v=${assetVersion(root, js)}"></script>` : ''}`;
}
